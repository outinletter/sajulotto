const fs = require('node:fs');
const path = require('node:path');
const astronomy = require(path.resolve(process.argv[2]));
const snapshot = JSON.parse(fs.readFileSync(process.argv[3], 'utf8'));
const names = ['소한','대한','입춘','우수','경칩','춘분','청명','곡우','입하','소만','망종','하지','소서','대서','입추','처서','백로','추분','한로','상강','입동','소설','대설','동지'];
const data = { source: snapshot.source, url: snapshot.url, retrievedAt: snapshot.retrievedAt, officialYears: [], normalizedEntries: [], rejectedYears: [], fallback: 'Astronomy Engine 2.1.19 / 태양 겉보기 황경', names, years: {} };
let maxDifferenceMinutes = 0;
for (let year = 1899; year <= 2027; year++) {
    const calculated = names.map((_, i) => {
        const start = new Date(Date.UTC(year, Math.floor(i / 2), i % 2 ? 15 : 1));
        const result = astronomy.SearchSunLongitude((285 + i * 15) % 360, start, 20);
        if (!result) throw Error(`Missing solar term ${year}/${i}`);
        return Math.round(result.date.getTime() / 60000);
    });
    const official = snapshot.years[year];
    if (official) {
        if (official.length !== 24) throw Error('Incomplete KASI year');
        let yearDifference = 0;
        const officialMinutes = names.map((name, i) => {
            const row = official.find(r => r.name === name);
            if (!row || !/^\d{8}$/.test(row.date) || !/^\d{4}$/.test(row.kst)) throw Error('Invalid KASI term');
            const d = row.date, t = row.kst;
            const hour = Number(t.slice(0,2)), min = Number(t.slice(2));
            if (hour > 23 || min > 60) throw Error('Invalid KASI clock');
            if (min === 60) data.normalizedEntries.push({year, name, rawKst:t, note:'분 60을 다음 시간 00분으로 정규화'});
            const minute = (Date.UTC(Number(d.slice(0,4)), Number(d.slice(4,6))-1, Number(d.slice(6,8)), hour, min) - 9*3600000) / 60000;
            if (!Number.isFinite(minute)) throw Error('Invalid KASI timestamp');
            yearDifference = Math.max(yearDifference, Math.abs(minute - calculated[i]));
            return minute;
        });
        if (yearDifference > 5) {
            data.rejectedYears.push({year, maxDifferenceMinutes:yearDifference, note:'공식 응답과 천문 계산 불일치: 천문 계산값으로 표시'});
            data.years[year] = calculated;
        } else {
            data.officialYears.push(year);
            data.years[year] = officialMinutes;
            maxDifferenceMinutes = Math.max(maxDifferenceMinutes, yearDifference);
        }
    } else data.years[year] = calculated;
}
if (maxDifferenceMinutes > 5) throw Error(`Ephemeris mismatch: ${maxDifferenceMinutes} min`);
data.overlapMaxDifferenceMinutes = maxDifferenceMinutes;
const output = '/* Public KASI data; astronomical fallback. Generated by scripts/build-solar-terms.cjs. No credentials. */\nwindow.SajuSolarTerms = ' + JSON.stringify(data) + ';\n';
for (const dir of ['vendor', 'ios/Web/vendor']) fs.writeFileSync(path.join(dir, 'solar-terms.js'), output);
console.log({years:Object.keys(data.years).length,officialYears:data.officialYears.length,maxDifferenceMinutes});
